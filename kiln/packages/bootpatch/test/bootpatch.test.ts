// bootpatch: unit tests + byte-exact comparisons against goldens made by the real CLI
// (patch-boot-magisk.sh in Docker, tools/branding/set-bootlogo.py). The whole patch with a frame's overlay is that
// frame's test (frames/aqara-s1-plus/installer/test/overlay.test.ts).
//
// The goldens contain Aqara's boot images and Magisk binaries, so they live outside the repo:
//   S1_WEB_GOLDEN=~/src/aqara-panel-backups/web-golden npm test
// (that path is also the default). Without them the golden tests are skipped; the unit tests run.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';

import { type Compressor, loadCompressor } from '../src/compress';
import { crc32 } from '../src/apk';
import {
  replaceBootlogo, vbmetaFlags, withVbmetaFlags,
} from '../src/index';

const GOLDEN = process.env.S1_WEB_GOLDEN ?? join(homedir(), 'src/aqara-panel-backups/web-golden');
const HAVE_GOLDEN = existsSync(join(GOLDEN, 'out/SHA256SUMS'));
const SKIP_MSG = `[bootpatch] golden tests SKIPPED: no goldens at ${GOLDEN} (set S1_WEB_GOLDEN; they are ` +
  `generated by gen.sh in that directory and are never committed)`;

const enc = new TextEncoder();
const g = (p: string) => new Uint8Array(readFileSync(join(GOLDEN, p)));
const sha256 = (d: Uint8Array) => createHash('sha256').update(d).digest('hex');

/** Equal bytes, reported by hash + first differing offset instead of a 32 MiB diff. */
function expectSameBytes(got: Uint8Array, want: Uint8Array, what: string) {
  if (got.length === want.length && Buffer.compare(got, want) === 0) return;
  let i = 0;
  while (i < got.length && i < want.length && got[i] === want[i]) i++;
  expect.fail(`${what}: differs (len ${got.length} vs ${want.length}, first diff @0x${i.toString(16)}; ` +
    `sha256 ${sha256(got)} vs ${sha256(want)})`);
}

let comp: Compressor;
beforeAll(async () => { comp = await loadCompressor(); });

it.runIf(!HAVE_GOLDEN)('golden fixtures are absent: golden tests skipped', () => { process.stderr.write(SKIP_MSG + '\n'); });

// ---------------------------------------------------------------------------------------------
it('crc32 (the zip reader in apk.ts)', () => {
  expect(crc32(enc.encode('123456789'))).toBe(0xcbf43926);
});

describe('compress (unit)', () => {
  it('round-trips and picks magiskboot BCJ filters', () => {
    const d = enc.encode('hello hello hello hello '.repeat(100));
    expectSameBytes(comp.gunzip(comp.gzip(d)), d, 'gzip');
    expectSameBytes(comp.unxz(comp.xz(d))!, d, 'xz');
    expect(comp.unxz(enc.encode('not xz'))).toBeNull();
    const elf = (m: number) => { const b = new Uint8Array(64); b.set([0x7f, 0x45, 0x4c, 0x46, 1, 1]); b[18] = m & 0xff; b[19] = m >> 8; return b; };
    expect(comp.bcjFilter(elf(0x28))).toBe(3); // ARM-Thumb
    expect(comp.bcjFilter(elf(0xb7))).toBe(4); // ARM64
    expect(comp.bcjFilter(elf(0x3e))).toBe(1); // x86
    expect(comp.bcjFilter(d)).toBe(0);
  });
});

describe('vbmeta (unit)', () => {
  it('reads and sets flags at BE offset 120', () => {
    const v = new Uint8Array(256);
    v.set(enc.encode('AVB0'));
    v[123] = 0;
    expect(vbmetaFlags(v)).toBe(0);
    const w = withVbmetaFlags(v, 3);
    expect(vbmetaFlags(w)).toBe(3);
    expect(vbmetaFlags(v)).toBe(0); // input untouched
    expect(() => vbmetaFlags(new Uint8Array(256))).toThrow(/AVB0/);
  });
});

// ---------------------------------------------------------------------------------------------
describe.skipIf(!HAVE_GOLDEN)('golden: compressors == magiskboot', () => {
  it('xz (compress=xz, 4 KiB sniff) of magisk and init-ld', () => {
    expectSameBytes(comp.xz(g('fixtures/compress/magisk.raw'), 4096), g('fixtures/compress/magisk.xz'), 'magisk.xz');
    expectSameBytes(comp.xz(g('fixtures/compress/init-ld.raw'), 4096), g('fixtures/compress/init-ld.xz'), 'init-ld.xz');
  });
  it('xz (cpio backup, full sniff) of the stock init', () => {
    expectSameBytes(comp.xz(g('fixtures/compress/init.raw')), g('fixtures/compress/init.xz'), '.backup/init.xz');
  });
  it('gzip best of a patched ramdisk', () => {
    expectSameBytes(comp.gzip(g('fixtures/compress/patched.cpio')), g('fixtures/compress/patched.golden.gz'), 'ramdisk gzip');
  });
});

describe.skipIf(!HAVE_GOLDEN)('golden: partitions', () => {
  it('replaceBootlogo == tools/branding/set-bootlogo.py', () => {
    expectSameBytes(replaceBootlogo(g('in/bootloader.img'), g('fixtures/bootlogo.bmp')), g('out/bootloader-glass-tile.img'), 'bootloader');
  });
  it('withVbmetaFlags(3) == the vbmeta fel-install.sh flashed', () => {
    const v = g('in/vbmeta.img');
    expect(vbmetaFlags(v)).toBe(0);
    expectSameBytes(withVbmetaFlags(v, 3), g('in/vbmeta.flags3.img'), 'vbmeta flags 3');
  });
});
